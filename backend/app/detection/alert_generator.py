from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.future import select
from sqlalchemy import update
from datetime import datetime, timezone, timedelta
from typing import Dict, Any
from app.database.models import Alert
import logging

logger = logging.getLogger(__name__)

class AlertGenerator:
    def __init__(self):
        # In-memory deduplication cache
        # { dedup_key: alert_id }
        self.recent_alerts = {}
        self.dedup_window_seconds = 300

    def _get_dedup_key(self, rule_name: str, source_ip: str) -> str:
        return f"{rule_name}-{source_ip}"

    async def generate_alert(self, db: AsyncSession, rule: Dict[str, Any], event: Dict[str, Any]):
        config = rule.get("configuration", {})
        
        source_ip = event.get("source_ip", "unknown")
        username = event.get("username")
        
        msg_template = config.get("message_template", "Alert generated by rule {rule_name}")
        description = msg_template.format(
            source_ip=source_ip,
            path=event.get("path", "unknown"),
            rule_name=rule.get("name")
        )
        
        dedup_key = self._get_dedup_key(rule.get("name"), source_ip)
        now = datetime.now(timezone.utc)
        
        # Check cache
        if dedup_key in self.recent_alerts:
            cache_entry = self.recent_alerts[dedup_key]
            if (now - cache_entry["time"]).total_seconds() < self.dedup_window_seconds:
                # Deduplicate: update count in DB
                alert_id = cache_entry["id"]
                try:
                    await db.execute(
                        update(Alert)
                        .where(Alert.id == alert_id)
                        .values(
                            event_count=Alert.event_count + 1,
                            last_seen_at=now
                        )
                    )
                    await db.commit()
                    logger.debug(f"Deduplicated alert {alert_id}")
                    # Update cache time
                    cache_entry["time"] = now
                    return
                except Exception as e:
                    logger.error(f"Error updating deduplicated alert: {e}")
                    await db.rollback()
        
        # Calculate initial risk score (can be enriched later by ML/TI)
        base_risk = 50.0
        if rule.get("severity") == "CRITICAL": base_risk = 90.0
        elif rule.get("severity") == "HIGH": base_risk = 75.0
        elif rule.get("severity") == "LOW": base_risk = 20.0

        # Create new alert
        new_alert = Alert(
            title=rule.get("name"),
            description=description,
            severity=rule.get("severity", "MEDIUM"),
            status="NEW",
            detection_type=rule.get("rule_type", "unknown"),
            source_ip=event.get("source_ip"),
            username=username,
            event_count=1,
            created_at=now,
            last_seen_at=now,
            risk_score=base_risk
        )
        
        db.add(new_alert)
        await db.commit()
        await db.refresh(new_alert)
        
        # Add to cache
        self.recent_alerts[dedup_key] = {
            "id": new_alert.id,
            "time": now
        }
        
        logger.info(f"Generated new alert: {new_alert.title} (ID: {new_alert.id})")
        
        # Broadcast real-time event
        from app.realtime.manager import manager
        await manager.broadcast({
            "type": "NEW_ALERT",
            "data": {
                "id": new_alert.id,
                "title": new_alert.title,
                "severity": new_alert.severity,
                "source_ip": new_alert.source_ip,
                "created_at": new_alert.created_at.isoformat(),
            }
        })

alert_generator = AlertGenerator()
